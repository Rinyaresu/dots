set -euo pipefail
extension=$1 work=$2
mkdir -p "$extension" "$work"
# A real npm tarball, with no registry or private Agent access.
printf '{"name":"bootstrap-dep","version":"1.0.0","type":"module","exports":"./index.js","scripts":{"postinstall":"exit 42"}}\n' > "$work/package.json"
printf 'export const answer = 42;\n' > "$work/index.js"
(cd "$work"; npm pack --ignore-scripts --silent)
tarball="$work/bootstrap-dep-1.0.0.tgz"
printf '{"name":"bootstrap-fixture","version":"1.0.0","dependencies":{"bootstrap-dep":"file:%s"}}\n' "$tarball" > "$extension/package.json"
(cd "$extension"; npm install --package-lock-only --ignore-scripts --no-audit --no-fund)
printf 'import { answer } from "bootstrap-dep";\nexport default () => { if (answer !== 42) throw new Error("wrong dependency"); };\n' > "$extension/index.ts"
# Allow the non-root VM session to read fixtures generated by the driver.
chmod a+r "$tarball"
